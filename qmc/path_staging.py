"""Free-conditional staging/bisection proposals and MCMC diagnostics for PIGS.

The (labelled-particle) continuum primitive-action target is inherited from
:mod:`qmc.interacting_path`. This module does NOT sample Bose permutations or
open-worldline off-diagonal sectors. For a fixed segment's endpoints, its
proposed interior has exactly the free periodic Brownian-bridge law (up to the
same ~8-sigma image truncation used by PeriodicFreePropagator). Consequently
only the *interior interaction potential* enters the MH acceptance ratio.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .interacting_path import InteractingPathConfig, PrimitiveInteractingPath, _integer


def periodic_bridge(kernel, rng, start, end, n_links: int, tau: float,
                    *, method: str = "staging") -> np.ndarray:
    """Conditional *free* Brownian bridge on an orthorhombic torus.

    ``start,end``: (n_selected_particles, 3). Result has ``n_links+1``
    beads. The 3D winding number is drawn with probability proportional to
    exp(-|end-start+nL|**2/(4*D*n_links*tau)), then the unwrapped bridge is
    generated by either staging (Gaussian cumulative increments conditioned
    on the endpoint) or recursive bisection. The two samplers have the same
    distribution; both endpoints remain fixed modulo the periodic cell.
    """
    n_links = _integer(n_links, "n_links", 2)
    tau = float(tau)
    if not np.isfinite(tau) or tau <= 0:
        raise ValueError("tau must be finite and positive")
    if method not in ("staging", "bisection"):
        raise ValueError("method must be staging or bisection")
    left = np.asarray(start, dtype=float)
    right = np.asarray(end, dtype=float)
    if (left.ndim != 2 or left.shape[1] != 3 or left.shape[0] < 1
            or right.shape != left.shape or not np.all(np.isfinite(left))
            or not np.all(np.isfinite(right))):
        raise ValueError("start/end must be matching finite (n_particles,3) arrays")
    left = kernel.cell.wrap(left)
    right = kernel.cell.wrap(right)
    N = len(left)
    D = kernel.kinetic_coefficient
    if not np.isfinite(D) or D <= 0:
        raise ValueError("kinetic coefficient must be positive")
    sigma_total = np.sqrt(2.0 * D * n_links * tau)
    end_unwrapped = np.empty_like(left)
    # Draw each independent lattice winding. Truncation to the same physical
    # 8-sigma image range as the periodic free kernel controls tail error.
    for axis, L in enumerate(kernel.cell.lengths):
        delta = right[:, axis] - left[:, axis]
        centered = delta - L * np.rint(delta / L)
        radius = max(1, int(np.ceil(0.5 + 8.0 * sigma_total / L)))
        shifts = np.arange(-radius, radius + 1, dtype=float) * L
        exponents = -0.5 * ((centered[:, None] + shifts) / sigma_total) ** 2
        weights = np.exp(exponents - np.max(exponents, axis=1, keepdims=True))
        probabilities = weights / np.sum(weights, axis=1, keepdims=True)
        # Vectorized inverse CDF, one independent draw per particle and axis.
        thresholds = rng.random(N)
        selected = np.sum(thresholds[:, None] > np.cumsum(probabilities, axis=1), axis=1)
        selected = np.minimum(selected, len(shifts) - 1)
        end_unwrapped[:, axis] = left[:, axis] + centered + shifts[selected]

    result = np.empty((n_links + 1, N, 3), dtype=float)
    result[0], result[-1] = left, end_unwrapped
    if method == "staging":
        increments = np.sqrt(2 * D * tau) * rng.normal(size=(n_links, N, 3))
        walk = np.concatenate((np.zeros((1, N, 3)), np.cumsum(increments, axis=0)))
        fraction = np.arange(n_links + 1, dtype=float)[:, None, None] / n_links
        result = left[None] + fraction * (end_unwrapped - left)[None] + walk - fraction * walk[-1]
    else:
        stack = [(0, n_links)]
        while stack:
            a, b = stack.pop()
            if b - a <= 1:
                continue
            middle = (a + b) // 2
            fraction = (middle - a) / (b - a)
            variance = 2 * D * tau * (middle - a) * (b - middle) / (b - a)
            result[middle] = ((1 - fraction) * result[a] + fraction * result[b]
                              + np.sqrt(variance) * rng.normal(size=(N, 3)))
            stack.extend(((a, middle), (middle, b)))
    wrapped = kernel.cell.wrap(result)
    wrapped[0] = left
    wrapped[-1] = right
    return wrapped


@dataclass(frozen=True)
class StagedPathConfig(InteractingPathConfig):
    bridge_probability: float = 0.65
    bridge_lengths: tuple[int, ...] = (2, 4, 8)
    bridge_method: str = "mixed"  # staging | bisection | mixed

    def validate(self):
        super().validate()
        p = float(self.bridge_probability)
        if not np.isfinite(p) or not 0 <= p <= 1:
            raise ValueError("bridge_probability must be in [0,1]")
        if self.bridge_method not in ("staging", "bisection", "mixed"):
            raise ValueError("bridge_method must be staging, bisection or mixed")
        if not isinstance(self.bridge_lengths, (tuple, list)) or not self.bridge_lengths:
            raise ValueError("bridge_lengths must be a nonempty sequence")
        for length in self.bridge_lengths:
            _integer(length, "bridge length", 2)
            if length > self.n_links:
                raise ValueError("bridge length cannot exceed n_links")
        if len(set(self.bridge_lengths)) != len(self.bridge_lengths):
            raise ValueError("bridge lengths must be distinct")
        return self


class StagedInteractingPath(PrimitiveInteractingPath):
    """Patch 15 path sampler with reversible blocked free-bridge proposals.

    Each bridge changes the path of ONE labelled particle between two fixed
    beads and is accepted using only the change in potential at interior
    beads. Endpoint trial amplitudes and all free-link weights cancel.
    Selectors (segment length, position, particle, method) are state-independent,
    so their probabilities cancel in the MH ratio as well.
    """

    def __init__(self, cell, potential, trial, n_particles,
                 config: StagedPathConfig = StagedPathConfig(), *, kinetic_coefficient=0.5):
        if not isinstance(config, StagedPathConfig):
            raise TypeError("StagedInteractingPath requires StagedPathConfig")
        super().__init__(cell, potential, trial, n_particles, config,
                         kinetic_coefficient=kinetic_coefficient)
        self._counts["staging"] = [0, 0]
        self._counts["bisection"] = [0, 0]

    def move_bridge(self, *, length: int | None = None, start: int | None = None,
                    particle: int | None = None, method: str | None = None):
        cfg = self.config
        if length is None:
            length = int(self.rng.choice(cfg.bridge_lengths))
        length = _integer(length, "length", 2)
        if length > cfg.n_links:
            raise ValueError("length must be <= n_links")
        if start is None:
            start = int(self.rng.integers(cfg.n_links - length + 1))
        if particle is None:
            particle = int(self.rng.integers(self.n_particles))
        if not (0 <= start <= cfg.n_links - length and 0 <= particle < self.n_particles):
            raise IndexError("segment start or particle is out of range")
        if method is None:
            method = ("staging" if self.rng.random() < 0.5 else "bisection") if cfg.bridge_method == "mixed" else cfg.bridge_method
        if method not in ("staging", "bisection"):
            raise ValueError("unknown bridge method")
        old = self.path
        proposed = old.copy()
        bridge = periodic_bridge(self.kernel, self.rng,
                                 old[start, particle:particle + 1],
                                 old[start + length, particle:particle + 1],
                                 length, cfg.time_step, method=method)
        proposed[start + 1:start + length, particle] = bridge[1:-1, 0]
        # The conditional Brownian-bridge proposal cancels the *entire*
        # free-link action. Only primitive interaction terms at changed beads
        # remain, with full tau weight because the endpoints are fixed.
        before = np.asarray(self.potential(old[start + 1:start + length]), dtype=float)
        after = np.asarray(self.potential(proposed[start + 1:start + length]), dtype=float)
        if (before.shape != (length - 1,) or after.shape != before.shape
                or not np.all(np.isfinite(before)) or not np.all(np.isfinite(after))):
            raise ValueError("potential must return finite per-bead values")
        log_ratio = -cfg.time_step * float(np.sum(after - before))
        return self._accept(method, proposed, log_ratio)

    def step(self):
        u = self.rng.random()
        cfg = self.config
        if u < cfg.bridge_probability:
            return self.move_bridge()
        # Distribute the remaining probability across Patch 15's existing
        # three move types without changing their relative proportions.
        u = (u - cfg.bridge_probability) / (1 - cfg.bridge_probability)
        if u < cfg.refresh_probability:
            return self.move_refresh()
        if u < cfg.refresh_probability + cfg.translate_probability:
            return self.move_translate()
        return self.move_bead()


@dataclass(frozen=True)
class AutocorrelationEstimate:
    mean: float
    variance: float
    tau_integrated: float
    effective_samples: float
    stderr: float
    n_samples: int
    window: int


def autocorrelation_estimate(series, *, max_lag: int | None = None, window_factor: float = 5.0):
    """FFT integrated autocorrelation time with a positive-pair window.

    Convention: ``tau_int=1/2+sum_{lag>=1} rho(lag)``, and
    ``N_eff=N/(2*tau_int)``. Stops when adjacent positive-sequence pairs
    become nonpositive or lag exceeds ``window_factor*tau_int``. This is a
    diagnostic (not a guaranteed confidence interval), particularly unreliable
    for short, strongly metastable MCMC chains. Constant series is exact.
    """
    x = np.asarray(series, dtype=float)
    if x.ndim != 1 or len(x) < 4 or not np.all(np.isfinite(x)):
        raise ValueError("series must be at least four finite samples")
    n = len(x)
    centered = x - np.mean(x)
    variance = float(np.mean(centered**2))
    if variance <= np.finfo(float).tiny:
        return AutocorrelationEstimate(float(x.mean()), 0.0, 0.5, float(n), 0.0, n, 0)
    if not np.isfinite(window_factor) or window_factor <= 0:
        raise ValueError("window_factor must be finite and positive")
    if max_lag is None:
        max_lag = max(1, min(n // 2, n - 1))
    else:
        max_lag = _integer(max_lag, "max_lag", 1)
        max_lag = min(max_lag, n - 1)
    fft = np.fft.rfft(centered, n=2*n)
    covariance = np.fft.irfft(fft * np.conj(fft), n=2*n)[:max_lag + 1]
    # Unbiased denominator n-lag: reduce attenuation of long-range correlation.
    acf = (covariance / (n - np.arange(max_lag + 1))) / variance
    tau_int, last = 0.5, 0
    for lag in range(1, max_lag + 1, 2):
        # Two-lag positive-sequence cutoff reduces spuriously large noise tails.
        pair = float(acf[lag] + (acf[lag + 1] if lag + 1 <= max_lag else 0.0))
        if pair <= 0:
            break
        tau_int += pair
        last = min(lag + 1, max_lag)
        if last >= window_factor * tau_int:
            break
    tau_int = max(0.5, float(tau_int))
    ess = min(float(n), n / (2 * tau_int))
    return AutocorrelationEstimate(float(x.mean()), variance, tau_int, ess,
                                   float(np.sqrt(variance / ess)), n, last)
